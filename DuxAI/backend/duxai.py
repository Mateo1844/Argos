#!/usr/bin/env python3
"""DUX-AI backend.

The QML widget calls this script for everything that is not UI:

    duxai.py ask       send a message to Claude (streams JSON lines on stdout)
    duxai.py list      list saved chats + how much disk space they use
    duxai.py load ID   print one saved chat
    duxai.py delete ID delete one chat (or "all")
    duxai.py capture   let the user select a screen region, print the image path
    duxai.py selection print the text currently highlighted anywhere on screen

Claude is reached through the Claude Code CLI (`claude -p`), so it runs on your
Pro/Max subscription login. No API key needed.

Every line this script prints is one JSON object, so QML can parse it easily.
Only the Python standard library is required (Pillow is optional and only used
to shrink big screenshots).
"""

import argparse
import base64
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import threading
import time
import uuid
from pathlib import Path

# ---------------------------------------------------------------- paths ----

IS_WINDOWS = os.name == "nt"
if IS_WINDOWS:   # C:\Users\<you>\AppData\Local\dux-ai
    DATA_DIR = Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local")) / "dux-ai"
else:            # ~/.local/share/dux-ai
    DATA_DIR = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share")) / "dux-ai"
CHATS_DIR = DATA_DIR / "chats"      # one JSON file per chat
IMAGES_DIR = DATA_DIR / "images"    # screenshots that were attached to chats
WORK_DIR = DATA_DIR / "workdir"     # empty folder claude runs in (no CLAUDE.md, no git)
CLAUDE_DIR = Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude"))

# Short system prompt. It replaces Claude Code's large coding-agent prompt,
# which is the single biggest token saving in this project.
SYSTEM_PROMPT = (
    "You are Claude, an assistant that lives in the user's desktop top bar "
    "(Linux, niri + DankMaterialShell). Be concise and direct: answer first, "
    "then add detail only if it helps. Use short Markdown (lists, code blocks) "
    "when useful. When the user attaches a screenshot, answer about what they "
    "selected. A message may start with [Active window: ...]: that is the app "
    "the user was looking at; 'this file/folder/page' usually refers to it."
)

# Agent mode keeps Claude Code's own (tool-using) system prompt and adds this.
AGENT_PROMPT = (
    "You are running as DUX-AI, an assistant in the user's desktop top bar "
    "(Linux, niri + DankMaterialShell), with access to their computer. Keep "
    "replies short. A message may start with [Active window: app - title]: "
    "'this folder/file/page' usually refers to that window (e.g. a Dolphin title "
    "is the folder path). Every change you make is shown to the user for "
    "approval; if they deny something, don't try to work around it."
)

# Added when the screen viewer is on (both modes).
SCREEN_PROMPT = (
    "You can look at the user's screen with the view_screen tool (active window, "
    "or full=true for the whole monitor). Use it only when the user refers to "
    "something on their screen that they didn't attach and the window title "
    "isn't enough. Don't mention the tool, just answer."
)
SCREEN_TOOL = "mcp__duxai__view_screen"

# Always blocked in agent mode, whatever the user clicks.
ALWAYS_DENY = ["Bash(sudo *)", "Bash(rm -rf *)", "Bash(rm -fr *)",
               "Read(~/.ssh/**)", "Edit(~/.ssh/**)", "Read(~/.gnupg/**)", "Edit(~/.gnupg/**)"]

# Flags that cut tokens/startup work. Each one is only passed if the installed
# `claude` version supports it (checked once via `claude --help`).
# Selected text longer than this is cut off (a whole page is ~3000 tokens).
MAX_QUOTE_CHARS = 20000

LEAN_FLAGS = ["--strict-mcp-config", "--disable-slash-commands", "--safe-mode"]


# Extra options for every subprocess: always UTF-8 (Windows would default to
# an old code page) and, on Windows, no black console window popping up.
SP = {"encoding": "utf-8", "errors": "replace"}
if IS_WINDOWS:
    SP["creationflags"] = 0x08000000   # CREATE_NO_WINDOW


def emit(**obj):
    """Print one JSON line and flush so QML receives it immediately."""
    print(json.dumps(obj), flush=True)


def now():
    return int(time.time())


# --------------------------------------------------------------- chats -----

def chat_path(chat_id):
    # Chat ids are generated by us (hex), but never trust input with paths.
    safe = "".join(c for c in chat_id if c.isalnum() or c in "-_")
    return CHATS_DIR / f"{safe}.json"


def load_chat(chat_id):
    try:
        return json.loads(chat_path(chat_id).read_text())
    except (OSError, ValueError):
        return None


def save_chat(chat):
    CHATS_DIR.mkdir(parents=True, exist_ok=True)
    path = chat_path(chat["id"])
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(chat, indent=1))
    tmp.replace(path)  # atomic: never leaves a half-written chat


def new_chat(model, effort):
    return {
        "id": uuid.uuid4().hex[:12],
        "title": "New chat",
        "created": now(),
        "updated": now(),
        "model": model,
        "effort": effort,
        "session_id": None,   # Claude Code session, used with --resume
        "cost_usd": 0.0,
        "messages": [],
    }


def token_stats(chat):
    """Token counts for the chat window's usage label.

    total   = everything sent + received over all turns (cached input included,
              since every follow-up re-reads the conversation)
    context = size of the conversation at the last turn
    last    = what the last answer cost: input, of which cached, and output
    """
    total, last = 0, None
    for msg in chat.get("messages", []):
        u = msg.get("usage")
        if not u:
            continue
        inp = sum(u.get(k) or 0 for k in ("input_tokens", "cache_read_input_tokens",
                                           "cache_creation_input_tokens"))
        out = u.get("output_tokens") or 0
        total += inp + out
        last = {"input": inp, "cached": u.get("cache_read_input_tokens") or 0, "output": out}
    return {"total": total, "context": (last["input"] + last["output"]) if last else 0, "last": last}


def make_title(text):
    """Title = start of the first message (free: no extra API call)."""
    text = " ".join(text.split())
    return (text[:48] + "…") if len(text) > 48 else (text or "Screenshot")


def transcript_paths(session_id):
    """Claude Code's own transcript files for a session (for size + delete)."""
    if not session_id:
        return []
    projects = CLAUDE_DIR / "projects"
    return list(projects.glob(f"*/{session_id}.jsonl")) + list(projects.glob(f"*/{session_id}"))


def path_size(path):
    if path.is_file():
        return path.stat().st_size
    total = 0
    for root, _dirs, files in os.walk(path):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(root, name))
            except OSError:
                pass
    return total


def all_chats():
    chats = []
    for file in CHATS_DIR.glob("*.json"):
        try:
            chats.append(json.loads(file.read_text()))
        except (OSError, ValueError):
            continue
    chats.sort(key=lambda c: c.get("updated", 0), reverse=True)
    return chats


def storage_bytes(chats):
    total = path_size(CHATS_DIR) if CHATS_DIR.exists() else 0
    total += path_size(IMAGES_DIR) if IMAGES_DIR.exists() else 0
    for chat in chats:
        for p in transcript_paths(chat.get("session_id")):
            total += path_size(p)
    return total


def human_size(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def delete_chat(chat):
    for msg in chat.get("messages", []):
        img = msg.get("image")
        if img and Path(img).parent == IMAGES_DIR:
            Path(img).unlink(missing_ok=True)
    for p in transcript_paths(chat.get("session_id")):
        shutil.rmtree(p, ignore_errors=True) if p.is_dir() else p.unlink(missing_ok=True)
    chat_path(chat["id"]).unlink(missing_ok=True)


# --------------------------------------------------------------- claude ----

def find_claude():
    native = Path.home() / ".local/bin/claude.exe"
    if IS_WINDOWS and native.exists():
        return str(native)   # the native installer; preferred over an npm "claude.cmd"
    found = shutil.which("claude")
    if found:
        return found
    for guess in (Path.home() / ".local/bin/claude", Path.home() / ".claude/local/claude",
                  Path.home() / ".local/bin/claude.exe"):
        if guess.exists():
            return str(guess)
    return None


def supported_flags(claude):
    """Which optional flags this claude version has. Cached per binary version."""
    cache = DATA_DIR / "claude-flags.json"
    key = f"{claude}:{os.stat(claude).st_mtime}"
    try:
        data = json.loads(cache.read_text())
        if data.get("key") == key:
            return set(data["flags"])
    except (OSError, ValueError, KeyError):
        pass
    try:
        help_text = subprocess.run([claude, "--help"], capture_output=True, text=True, **SP, timeout=20).stdout
    except (OSError, subprocess.SubprocessError):
        help_text = ""
    flags = [f for f in LEAN_FLAGS + ["--effort", "--tools", "--permission-prompt-tool"] if f in help_text]
    if '"manual"' in help_text:
        flags.append("mode:manual")   # newer name of the "default" permission mode
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps({"key": key, "flags": flags}))
    return set(flags)


def mcp_config(target_window=""):
    """Our own tiny tool server (this script with `mcp`): gives Claude view_screen.

    target_window (Windows): handle of the window the user was looking at, so a
    screenshot shows that window and not the chat window in front of it.
    """
    server = {"type": "stdio", "command": sys.executable, "args": [str(Path(__file__).resolve()), "mcp"]}
    if target_window:
        server["env"] = {"DUXAI_TARGET_WINDOW": str(target_window)}
    return json.dumps({"mcpServers": {"duxai": server}})


def lean_env(screen):
    """Environment for normal chat. --safe-mode would also block our own tool
    server, so with the screen viewer on we keep CLAUDE.md/memory out this way."""
    env = dict(os.environ)
    if screen:
        env["CLAUDE_CODE_DISABLE_CLAUDE_MDS"] = "1"
        env["CLAUDE_CODE_DISABLE_AUTO_MEMORY"] = "1"
    return env


def build_command(claude, flags, model, effort, session_id, web, extra_prompt, screen=False, target_window=""):
    system = SYSTEM_PROMPT + ("\n\n" + SCREEN_PROMPT if screen else "")
    system += ("\n\n" + extra_prompt.strip() if extra_prompt.strip() else "")
    cmd = [
        claude, "-p",
        "--input-format", "stream-json",      # lets us send images as content blocks
        "--output-format", "stream-json",
        "--verbose", "--include-partial-messages",  # token-by-token streaming
        "--model", model,
        "--system-prompt", system,
    ]
    if "--effort" in flags and effort:
        cmd += ["--effort", effort]
    if "--tools" in flags:
        # No tools = no tool definitions in the prompt (saves tokens).
        # With web search on, only the two web tools are offered.
        cmd += ["--tools", "WebSearch,WebFetch" if web else ""]
    allowed = (["WebSearch", "WebFetch"] if web else []) + ([SCREEN_TOOL] if screen else [])
    if allowed:
        cmd += ["--allowedTools", ",".join(allowed)]
    if screen:
        cmd += ["--mcp-config", mcp_config(target_window)]
    cmd += [f for f in LEAN_FLAGS if f in flags and not (screen and f == "--safe-mode")]
    if session_id:
        cmd += ["--resume", session_id]
    return cmd


def rule_path(folder):
    """Folder from the settings -> path for a permission rule.

    Claude Code rules use ~/x for home-relative and //x for absolute paths.
    """
    folder = folder.strip().rstrip("/")
    if folder.startswith("~/") or folder == "~":
        return folder
    if folder.startswith("/"):
        return "/" + folder
    return "~/" + folder   # "Documents/KUL" -> under home


def split_folders(text):
    return [f for f in (x.strip() for x in (text or "").split(",")) if f]


def permission_rules(level, trusted, ask_dirs, deny_dirs, screen=False):
    """Build the allow/ask/deny rules for agent mode.

    deny  > ask > allow: a denied folder stays denied even if allowed elsewhere.
    level "ask_all"     - every action needs approval, even reading files
          "ask_changes" - reading is free, every change asks (Claude Code default)
          "trusted"     - edits inside the trusted folders are free, rest asks
    """
    allow, ask, deny = [], [], list(ALWAYS_DENY)
    for d in split_folders(deny_dirs):
        deny += [f"Read({rule_path(d)}/**)", f"Edit({rule_path(d)}/**)"]
    for d in split_folders(ask_dirs):
        ask += [f"Edit({rule_path(d)}/**)"]
    if level == "ask_all":
        ask += ["Read", "Glob", "Grep", "Bash", "Edit", "WebFetch", "WebSearch"]
    elif level == "trusted":
        allow += [f"Edit({rule_path(d)}/**)" for d in split_folders(trusted)]
    if screen and level != "ask_all":
        allow.append(SCREEN_TOOL)        # looking at the screen doesn't change anything
    return {"allow": allow, "ask": ask, "deny": deny}


def build_agent_command(claude, flags, model, effort, session_id, extra_prompt, rules, screen=False,
                        target_window=""):
    """Agent mode: Claude Code with its normal tools, your settings and MCP
    servers, and every permission question sent to us (shown as buttons)."""
    system = AGENT_PROMPT + ("\n\n" + SCREEN_PROMPT if screen else "")
    system += ("\n\n" + extra_prompt.strip() if extra_prompt.strip() else "")
    cmd = [
        claude, "-p",
        "--input-format", "stream-json",
        "--output-format", "stream-json",
        "--verbose", "--include-partial-messages",
        "--model", model,
        "--append-system-prompt", system,
        "--permission-prompt-tool", "stdio",   # ask us instead of a terminal prompt
        "--permission-mode", "manual" if "mode:manual" in flags else "default",
        "--settings", json.dumps({"permissions": rules}),
        "--disallowedTools", "AskUserQuestion",
    ]
    if "--effort" in flags and effort:
        cmd += ["--effort", effort]
    if screen:
        cmd += ["--mcp-config", mcp_config(target_window)]
    if session_id:
        cmd += ["--resume", session_id]
    return cmd


def describe_tool(name, inp):
    """Short human description of a tool call, for the chat and the approve card."""
    inp = inp or {}
    home = str(Path.home())
    short = lambda v: str(v).replace(home, "~")
    if name == "Bash":
        return "Run: " + short(inp.get("command", ""))
    if name in ("Edit", "MultiEdit"):
        return "Edit " + short(inp.get("file_path", ""))
    if name == "Write":
        return "Write " + short(inp.get("file_path", ""))
    if name == "Read":
        return "Read " + short(inp.get("file_path", ""))
    if name in ("Glob", "Grep"):
        return f"Search {short(inp.get('path', '') or '.')} for {inp.get('pattern', '')}"
    if name == "WebFetch":
        return "Open " + inp.get("url", "")
    if name == "WebSearch":
        return "Search the web: " + inp.get("query", "")
    if name == "TodoWrite":
        return "Update plan"
    detail = json.dumps(inp)[:120]
    return f"{name} {detail}"


def prepare_image(path, max_side):
    """Return (media_type, base64) for an image, shrunk if it is large.

    Image tokens grow with pixel count (~ width*height/750), so shrinking a
    big screenshot is a cheap way to save tokens. Needs Pillow; without it
    the image is sent as-is (Claude also downsizes very large images itself).
    """
    data = Path(path).read_bytes()
    media = "image/jpeg" if path.lower().endswith((".jpg", ".jpeg")) else "image/png"
    if max_side > 0:
        try:
            from io import BytesIO
            from PIL import Image
            img = Image.open(BytesIO(data))
            if max(img.size) > max_side:
                img.thumbnail((max_side, max_side))
                out = BytesIO()
                img.save(out, format="PNG", optimize=True)
                data, media = out.getvalue(), "image/png"
        except Exception:
            pass
    return media, base64.b64encode(data).decode()


def friendly_error(text):
    low = text.lower()
    if "login" in low or "not logged in" in low or "authentication" in low or "401" in low:
        return "Claude Code is not logged in. Open a terminal, run `claude` once and use /login."
    if "rate" in low and "limit" in low or "usage limit" in low:
        return "Usage limit reached for your plan. Try again later or pick a smaller model."
    return text.strip()[-600:] or "Claude exited without an answer."


def cmd_ask(args):
    claude = find_claude()
    if not claude:
        emit(type="error", message="The `claude` command was not found. Install Claude Code first (see README).")
        return 1

    chat = load_chat(args.chat) if args.chat else None
    if chat is None:
        chat = new_chat(args.model, args.effort)
    emit(type="start", chat=chat["id"])

    # A deleted/missing transcript can't be resumed: start a fresh session.
    session_id = chat.get("session_id")
    if session_id and not transcript_paths(session_id):
        session_id = None

    # --- build the user message (optional image + text) ---
    content = []
    image_path = None
    if args.image and Path(args.image).is_file():
        image_path = str(Path(args.image).resolve())
        media, b64 = prepare_image(image_path, args.max_image_side)
        content.append({"type": "image", "source": {"type": "base64", "media_type": media, "data": b64}})
    quote = args.quote.strip()[:MAX_QUOTE_CHARS]
    window = args.window.strip()[:300]
    prompt = args.prompt or ("What is this?" if image_path else "Explain this." if quote else "")
    if quote:
        prompt = f"<selected_text>\n{quote}\n</selected_text>\n\n{prompt}"
    if window:
        prompt = f"[Active window: {window}]\n\n{prompt}"
    content.append({"type": "text", "text": prompt})

    if not chat["messages"]:
        chat["title"] = make_title(args.prompt or quote or "Screenshot")
    chat["messages"].append({"role": "user", "text": args.prompt, "image": image_path,
                             "quote": quote, "window": window, "agent": args.agent, "time": now()})
    chat.update(model=args.model, effort=args.effort, updated=now())
    save_chat(chat)

    # --- run claude ---
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    flags = supported_flags(claude)
    if args.agent:
        rules = permission_rules(args.perm, args.trusted, args.ask_dirs, args.deny_dirs, args.screen)
        cmd = build_agent_command(claude, flags, args.model, args.effort, session_id, args.extra, rules,
                                  args.screen, args.target_window)
        cwd, env = Path.home(), None   # so "~/Downloads" etc. are inside its working folder
    else:
        cmd = build_command(claude, flags, args.model, args.effort, session_id, args.web, args.extra,
                            args.screen, args.target_window)
        cwd, env = WORK_DIR, lean_env(args.screen)
    errfile = tempfile.TemporaryFile(mode="w+")
    proc = subprocess.Popen(cmd, cwd=cwd, env=env, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=errfile, text=True, **SP, bufsize=1)
    write_lock = threading.Lock()

    def send_to_claude(obj):
        with write_lock:
            try:
                proc.stdin.write(json.dumps(obj) + "\n")
                proc.stdin.flush()
            except (BrokenPipeError, ValueError, OSError):
                pass

    # Messages from the widget arrive on our stdin, one JSON object per line:
    #   {"id": ..., "allow": true/false}   answer to an Allow/Deny card
    #   {"stop": true}                     stop button (used on Windows, which has no SIGTERM)
    def read_widget_messages():
        for line in sys.stdin:
            try:
                msg = json.loads(line)
            except ValueError:
                continue
            if msg.get("stop"):
                on_stop(None, None)
                continue
            try:
                req = pending.pop(msg["id"])
            except KeyError:
                continue
            if msg.get("allow"):
                reply = {"behavior": "allow", "updatedInput": req}
            else:
                reply = {"behavior": "deny", "message": "The user denied this action."}
            send_to_claude({"type": "control_response",
                            "response": {"subtype": "success", "request_id": msg["id"], "response": reply}})

    pending = {}   # request_id -> tool input
    stopped = False

    def on_stop(_sig, _frame):
        # The widget's stop button: stop claude too, keep the partial answer.
        nonlocal stopped
        stopped = True
        if proc.poll() is None:
            if IS_WINDOWS:
                proc.terminate()
            else:
                proc.send_signal(signal.SIGINT)

    threading.Thread(target=read_widget_messages, daemon=True).start()

    signal.signal(signal.SIGTERM, on_stop)
    signal.signal(signal.SIGINT, on_stop)

    send_to_claude({"type": "user", "message": {"role": "user", "content": content},
                    "parent_tool_use_id": None, "session_id": session_id or ""})

    text, result, thinking_sent, steps = "", None, False, []
    try:
        for line in proc.stdout:
            try:
                ev = json.loads(line)
            except ValueError:
                continue
            kind = ev.get("type")
            if kind == "system" and ev.get("subtype") == "init":
                chat["session_id"] = ev.get("session_id") or chat.get("session_id")
            elif kind == "stream_event":
                e = ev.get("event", {})
                if e.get("type") == "content_block_delta":
                    delta = e.get("delta", {})
                    if delta.get("type") == "text_delta":
                        text += delta.get("text", "")
                        emit(type="text", text=delta.get("text", ""))
                    elif delta.get("type") == "thinking_delta" and not thinking_sent:
                        thinking_sent = True
                        emit(type="status", text="Thinking…")
                elif e.get("type") == "content_block_start":
                    block = e.get("content_block", {})
                    if block.get("type") in ("tool_use", "server_tool_use"):
                        name = block.get("name", "")
                        emit(type="status", text="Looking at your screen…" if name == SCREEN_TOOL
                             else "Searching the web…" if name.startswith("Web") or block.get("type") == "server_tool_use"
                             else "Working…")
                    elif block.get("type") == "text":
                        thinking_sent = False
                        emit(type="status", text="")
            elif kind == "assistant" and not ev.get("parent_tool_use_id"):
                # Log what Claude does ("Read ~/x", "Run: ls") as small steps.
                for block in ev.get("message", {}).get("content", []):
                    if block.get("type") == "tool_use" and block.get("name") == SCREEN_TOOL:
                        emit(type="status", text="Looking at your screen…")   # not logged as a step
                    elif block.get("type") == "tool_use":
                        step = describe_tool(block.get("name"), block.get("input"))
                        steps.append(step)
                        emit(type="step", text=step)
            elif kind == "control_request":
                req = ev.get("request", {})
                if req.get("subtype") == "can_use_tool":
                    pending[ev["request_id"]] = req.get("input", {})
                    emit(type="permission", id=ev["request_id"], tool=req.get("tool_name", ""),
                         summary=describe_tool(req.get("tool_name"), req.get("input")),
                         plain=str((req.get("input") or {}).get("description") or ""),
                         reason=req.get("decision_reason") or req.get("description") or "")
                else:
                    send_to_claude({"type": "control_response", "response": {
                        "subtype": "error", "request_id": ev.get("request_id"),
                        "error": "Not supported by DUX-AI"}})
            elif kind == "control_cancel_request":
                pending.pop(ev.get("request_id"), None)
                emit(type="permission_cancel", id=ev.get("request_id"))
            elif kind == "result":
                result = ev
                break
    finally:
        with write_lock:
            try:
                proc.stdin.close()   # only now: closing early could cancel the turn
            except OSError:
                pass
        try:
            proc.wait(timeout=15)
        except subprocess.TimeoutExpired:
            proc.kill()

    # --- save + report ---
    if result and not result.get("is_error"):
        final = result.get("result") or text
        cost = float(result.get("total_cost_usd") or 0)
        usage = result.get("usage") or {}
        chat["session_id"] = result.get("session_id") or chat.get("session_id")
        chat["cost_usd"] = cost  # claude reports the running total for the session
        chat["messages"].append({"role": "assistant", "text": final, "time": now(), "steps": steps,
                                 "usage": {k: usage.get(k) for k in ("input_tokens", "output_tokens",
                                                                     "cache_read_input_tokens",
                                                                     "cache_creation_input_tokens")}})
        chat["updated"] = now()
        save_chat(chat)
        emit(type="done", chat=chat["id"], text=final, usage=usage, cost=cost, tokens=token_stats(chat),
             steps=steps)
        return 0

    if stopped:
        if text:
            chat["messages"].append({"role": "assistant", "text": text + "\n\n*(stopped)*", "time": now(),
                                     "steps": steps})
        save_chat(chat)
        emit(type="done", chat=chat["id"], text=text + ("\n\n*(stopped)*" if text else "*(stopped)*"),
             stopped=True)
        return 0

    errfile.seek(0)
    message = (result or {}).get("result") or errfile.read()
    save_chat(chat)
    emit(type="error", chat=chat["id"], message=friendly_error(message))
    return 1


