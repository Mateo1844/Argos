def cmd_capture(args):
    """Region screenshot (or the focused window with --window).

    Prefers DMS's own tool, else grim+slurp.
    """
    IMAGES_DIR.mkdir(parents=True, exist_ok=True)
    name = time.strftime("shot-%Y%m%d-%H%M%S")
    path = None
    if shutil.which("dms"):
        mode = ["window"] if args.window else ["region", "--no-confirm", "--reset"]
        out = subprocess.run(
            ["dms", "screenshot", *mode, "--no-clipboard", "--no-notify",
             "--json", "-d", str(IMAGES_DIR), "--filename", name + ".png"],
            capture_output=True, text=True, **SP)
        for line in out.stdout.splitlines():
            try:
                meta = json.loads(line)
            except ValueError:
                continue
            if meta.get("status") == "success" or meta.get("path"):
                path = meta.get("path")
    elif shutil.which("grim") and shutil.which("slurp"):
        geom = subprocess.run(["slurp"], capture_output=True, text=True, **SP)
        if geom.returncode == 0 and geom.stdout.strip():
            path = str(IMAGES_DIR / (name + ".png"))
            subprocess.run(["grim", "-g", geom.stdout.strip(), path])
    else:
        emit(type="error", message="No screenshot tool found (need `dms` or grim + slurp).")
        return 1

    if path and Path(path).is_file() and Path(path).stat().st_size > 0:
        emit(type="captured", path=str(Path(path).resolve()))
        return 0
    emit(type="cancelled")
    return 0


def active_window():
    """(app, title) of the focused window, via niri or Hyprland."""
    try:
        if shutil.which("niri"):
            out = subprocess.run(["niri", "msg", "--json", "focused-window"],
                                 capture_output=True, text=True, **SP, timeout=3)
            win = json.loads(out.stdout or "null") or {}
            app, title = win.get("app_id") or "", win.get("title") or ""
        elif shutil.which("hyprctl"):
            out = subprocess.run(["hyprctl", "activewindow", "-j"], capture_output=True, text=True, **SP, timeout=3)
            win = json.loads(out.stdout or "{}") or {}
            app, title = win.get("class") or "", win.get("title") or ""
        else:
            return "", ""
    except (OSError, ValueError, subprocess.SubprocessError):
        return "", ""
    # "org.kde.dolphin" -> "Dolphin"
    app = app.split(".")[-1].replace("-", " ").strip().title() if app else ""
    return app, title.strip()


def take_screenshot(full=False):
    """Screenshot of the active window (or whole monitor). Returns a Path or None.

    Keeps only the last 10 of these in images/agent.
    """
    folder = IMAGES_DIR / "agent"
    folder.mkdir(parents=True, exist_ok=True)
    for old in sorted(folder.glob("*.png"))[:-9]:
        old.unlink(missing_ok=True)
    path = folder / time.strftime("screen-%Y%m%d-%H%M%S.png")
    if IS_WINDOWS:
        import winutil   # Windows-only helpers next to this file
        hwnd = int(os.environ.get("DUXAI_TARGET_WINDOW") or 0) or None
        return path if winutil.screenshot(path, hwnd, full) else None
    if shutil.which("dms"):
        out = subprocess.run(["dms", "screenshot", "full" if full else "window", "--no-clipboard",
                              "--no-notify", "--json", "-d", str(folder), "--filename", path.name],
                             capture_output=True, text=True, **SP)
        for line in out.stdout.splitlines():
            try:
                meta = json.loads(line)
            except ValueError:
                continue
            if meta.get("path"):
                path = Path(meta["path"])
    elif shutil.which("grim"):
        subprocess.run(["grim", str(path)])
    return path if path.is_file() and path.stat().st_size > 0 else None


def cmd_mcp(_args):
    """Minimal MCP server (JSON-RPC over stdin/stdout) with one tool: view_screen.

    Claude Code starts this itself (see mcp_config). The screenshot goes back
    to Claude as an image, so the user never sees a command for it.
    """
    tool = {
        "name": "view_screen",
        "description": "Take a screenshot of the user's active window (or the whole monitor with "
                       "full=true) and look at it.",
        "inputSchema": {"type": "object", "properties": {
            "full": {"type": "boolean", "description": "Whole monitor instead of the active window"}}},
    }
    for line in sys.stdin:
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        if "id" not in msg:
            continue   # notifications need no answer
        method, result = msg.get("method"), None
        if method == "initialize":
            result = {"protocolVersion": msg.get("params", {}).get("protocolVersion", "2025-06-18"),
                      "capabilities": {"tools": {}}, "serverInfo": {"name": "duxai", "version": "0.1"}}
        elif method == "tools/list":
            result = {"tools": [tool]}
        elif method == "tools/call":
            full = bool(msg.get("params", {}).get("arguments", {}).get("full"))
            shot = take_screenshot(full)
            if shot:
                media, b64 = prepare_image(str(shot), 1280)
                result = {"content": [{"type": "image", "data": b64, "mimeType": media}]}
            else:
                result = {"content": [{"type": "text", "text": "Screenshot failed."}], "isError": True}
        elif method == "ping":
            result = {}
        if result is None:
            reply = {"jsonrpc": "2.0", "id": msg["id"], "error": {"code": -32601, "message": "Unknown method"}}
        else:
            reply = {"jsonrpc": "2.0", "id": msg["id"], "result": result}
        print(json.dumps(reply), flush=True)
    return 0


